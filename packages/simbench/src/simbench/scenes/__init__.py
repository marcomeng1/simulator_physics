"""Scene registry: name -> factory(**overrides) -> Scene."""

from simbench.scenes import deform, g1, insertion, panda, patch, primitives, sweep, thin

SCENES = {
    "slide": primitives.slide,
    "drop": primitives.drop,
    "hinge": primitives.hinge,
    "hinge-plastic": primitives.hinge_plastic,
    "collision-chain": primitives.collision_chain,
    "panda-effort": panda.effort,
    "panda-tracking": panda.tracking,
    "grasp": panda.grasp,
    "stack": panda.stack,
    "push": panda.push,
    "sweep": sweep.sweep,
    "insertion": insertion.insertion,
    "ball-compress": deform.compress,
    "ball-grasp": deform.grasp,
    "card-catch": thin.card_catch,
    "tumble": thin.tumble,
    "sheet": deform.sheet,
    "twist": patch.twist,
    "g1-walk": g1.walk,
}


def make(name: str, **overrides):
    return SCENES[name](**overrides)


def tape_specs() -> list[dict]:
    """Every controller tape a plan needs (generated by `simbench make-tapes`)."""
    return panda.tape_specs() + sweep.tape_specs() + deform.tape_specs()
